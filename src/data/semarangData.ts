// Helper functions for computing aggregates and filter views
export function getAreaById(id: string): AreaIntelligence | undefined {
  return SEMARANG_AREAS.find((a) => a.id === id);
}

export function getAreasByRole(role: StrategicRole): AreaIntelligence[] {
  return SEMARANG_AREAS.filter((a) => a.strategicRole === role);
}

export function getTopRankedArea(objective: 'retention' | 'defense' | 'acquisition' | 'expansion'): AreaIntelligence | null {
  const eligible = SEMARANG_AREAS.filter((a) => a.objectives[objective].eligible && a.objectives[objective].rank !== null);
  if (eligible.length === 0) return null;
  return eligible.sort((a, b) => (a.objectives[objective].rank || 99) - (b.objectives[objective].rank || 99))[0];
}

